-- RLS Policies for `tenants` (keyed by `id`)
DROP POLICY IF EXISTS tenant_isolation_policy ON tenants;
CREATE POLICY tenant_isolation_policy ON tenants
    AS PERMISSIVE FOR ALL TO maxi_loop_app
    USING (id = app_current_tenant_id())
    WITH CHECK (id = app_current_tenant_id());

DROP POLICY IF EXISTS worker_cross_tenant_policy ON tenants;
CREATE POLICY worker_cross_tenant_policy ON tenants
    AS PERMISSIVE FOR ALL TO maxi_loop_worker
    USING (true)
    WITH CHECK (id > 0);

-- RLS Policies for `users` (visible in tenant context only if member of current tenant)
DROP POLICY IF EXISTS tenant_isolation_select_policy ON users;
CREATE POLICY tenant_isolation_select_policy ON users
    AS PERMISSIVE FOR SELECT TO maxi_loop_app
    USING (
        EXISTS (
            SELECT 1 FROM memberships m
            WHERE m.user_id = users.id
              AND m.tenant_id = app_current_tenant_id()
        )
    );

DROP POLICY IF EXISTS tenant_isolation_update_policy ON users;
CREATE POLICY tenant_isolation_update_policy ON users
    AS PERMISSIVE FOR UPDATE TO maxi_loop_app
    USING (
        EXISTS (
            SELECT 1 FROM memberships m
            WHERE m.user_id = users.id
              AND m.tenant_id = app_current_tenant_id()
        )
    )
    WITH CHECK (
        EXISTS (
            SELECT 1 FROM memberships m
            WHERE m.user_id = users.id
              AND m.tenant_id = app_current_tenant_id()
        )
    );

DROP POLICY IF EXISTS worker_cross_tenant_policy ON users;
CREATE POLICY worker_cross_tenant_policy ON users
    AS PERMISSIVE FOR ALL TO maxi_loop_worker
    USING (true)
    WITH CHECK (true);

-- Helper procedure to attach standard `tenant_id = app_current_tenant_id()` RLS policies
DO $$
DECLARE
    tbl TEXT;
BEGIN
    FOREACH tbl IN ARRAY ARRAY[
        'workspaces',
        'projects',
        'memberships',
        'sessions',
        'issues',
        'events',
        'issue_hourly_counters'
    ]
    LOOP
        EXECUTE format('DROP POLICY IF EXISTS tenant_isolation_policy ON %I', tbl);
        EXECUTE format(
            'CREATE POLICY tenant_isolation_policy ON %I AS PERMISSIVE FOR ALL TO maxi_loop_app '
            'USING (tenant_id = app_current_tenant_id()) '
            'WITH CHECK (tenant_id = app_current_tenant_id())',
            tbl
        );

        EXECUTE format('DROP POLICY IF EXISTS worker_cross_tenant_policy ON %I', tbl);
        EXECUTE format(
            'CREATE POLICY worker_cross_tenant_policy ON %I AS PERMISSIVE FOR ALL TO maxi_loop_worker '
            'USING (true) '
            'WITH CHECK (tenant_id > 0)',
            tbl
        );
    END LOOP;
END
$$;

