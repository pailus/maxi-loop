-- Daily partition helper for `events` (idempotent, applies RLS + policies + grants to child partition)
CREATE OR REPLACE FUNCTION ensure_events_partition(target_date DATE)
RETURNS TEXT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    part_name TEXT;
    start_ts TIMESTAMPTZ;
    end_ts TIMESTAMPTZ;
BEGIN
    IF target_date IS NULL THEN
        RAISE EXCEPTION 'target_date must not be null';
    END IF;

    part_name := format('events_%s', to_char(target_date, 'YYYY_MM_DD'));
    start_ts := (target_date::timestamp AT TIME ZONE 'UTC');
    end_ts := ((target_date + 1)::timestamp AT TIME ZONE 'UTC');

    EXECUTE format(
        'CREATE TABLE IF NOT EXISTS %I PARTITION OF events FOR VALUES FROM (%L) TO (%L)',
        part_name,
        start_ts,
        end_ts
    );

    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', part_name);
    EXECUTE format('ALTER TABLE %I FORCE ROW LEVEL SECURITY', part_name);

    IF NOT EXISTS (
        SELECT 1 FROM pg_policies
        WHERE schemaname = 'public' AND tablename = part_name AND policyname = 'tenant_isolation_policy'
    ) THEN
        EXECUTE format(
            'CREATE POLICY tenant_isolation_policy ON %I AS PERMISSIVE FOR ALL TO maxi_loop_app '
            'USING (tenant_id = app_current_tenant_id()) '
            'WITH CHECK (tenant_id = app_current_tenant_id())',
            part_name
        );
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_policies
        WHERE schemaname = 'public' AND tablename = part_name AND policyname = 'worker_cross_tenant_policy'
    ) THEN
        EXECUTE format(
            'CREATE POLICY worker_cross_tenant_policy ON %I AS PERMISSIVE FOR ALL TO maxi_loop_worker '
            'USING (true) '
            'WITH CHECK (tenant_id > 0)',
            part_name
        );
    END IF;

    EXECUTE format(
        'GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE %I TO maxi_loop_app, maxi_loop_worker',
        part_name
    );

    RETURN part_name;
END;
$$;

REVOKE ALL ON FUNCTION ensure_events_partition(DATE) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION ensure_events_partition(DATE) TO maxi_loop_worker;

-- Pre-create partitions around current UTC date (-1 day to +7 days)
DO $$
DECLARE
    day_offset INTEGER;
    utc_today DATE := (NOW() AT TIME ZONE 'UTC')::DATE;
BEGIN
    FOR day_offset IN -1..7 LOOP
        PERFORM ensure_events_partition(utc_today + day_offset);
    END LOOP;
END
$$;
