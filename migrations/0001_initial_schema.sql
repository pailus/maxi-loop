-- 0001_initial_schema.sql
-- Phase 1 foundation schema:
--   - Roles: maxi_loop_app (tenant-scoped RLS) and maxi_loop_worker (cross-tenant ingest/maintenance)
--   - Hierarchy: tenants -> workspaces -> projects
--   - Auth & RBAC: users, memberships, sessions
--   - Core data: issues, daily-partitioned events, issue_hourly_counters
--   - Row-Level Security policies enforced via transaction-local `app.tenant_id`

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'maxi_loop_app') THEN
        CREATE ROLE maxi_loop_app NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOBYPASSRLS;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'maxi_loop_worker') THEN
        CREATE ROLE maxi_loop_worker NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOBYPASSRLS;
    END IF;

    EXECUTE format('GRANT maxi_loop_app TO %I', current_user);
    EXECUTE format('GRANT maxi_loop_worker TO %I', current_user);
END
$$;

GRANT USAGE ON SCHEMA public TO maxi_loop_app, maxi_loop_worker;

-- Fail-closed helper that parses transaction-local `app.tenant_id` into BIGINT (or NULL if unset/invalid).
CREATE OR REPLACE FUNCTION app_current_tenant_id()
RETURNS BIGINT
LANGUAGE sql
STABLE
AS $$
    SELECT CASE
        WHEN NULLIF(current_setting('app.tenant_id', true), '') ~ '^[0-9]+$'
        THEN NULLIF(current_setting('app.tenant_id', true), '')::BIGINT
        ELSE NULL
    END;
$$;

GRANT EXECUTE ON FUNCTION app_current_tenant_id() TO maxi_loop_app, maxi_loop_worker;

-- 1. Tenants
CREATE TABLE IF NOT EXISTS tenants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug TEXT NOT NULL UNIQUE CHECK (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$' AND char_length(slug) <= 64),
    name TEXT NOT NULL CHECK (char_length(btrim(name)) BETWEEN 1 AND 128),
    retention_days SMALLINT NOT NULL DEFAULT 30 CHECK (retention_days BETWEEN 1 AND 3650),
    is_default BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS tenants_single_default_idx
    ON tenants (is_default) WHERE is_default = TRUE;

-- 2. Workspaces (leading tenant_id in primary key and indexes)
CREATE TABLE IF NOT EXISTS workspaces (
    tenant_id BIGINT NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    slug TEXT NOT NULL CHECK (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$' AND char_length(slug) <= 64),
    name TEXT NOT NULL CHECK (char_length(btrim(name)) BETWEEN 1 AND 128),
    retention_days_override SMALLINT CHECK (
        retention_days_override IS NULL OR (retention_days_override BETWEEN 1 AND 3650)
    ),
    is_default BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (tenant_id, id),
    UNIQUE (tenant_id, slug)
);

CREATE UNIQUE INDEX IF NOT EXISTS workspaces_id_unique_idx ON workspaces (id);
CREATE UNIQUE INDEX IF NOT EXISTS workspaces_single_default_per_tenant_idx
    ON workspaces (tenant_id, is_default) WHERE is_default = TRUE;

-- 3. Projects (leading tenant_id in primary key and indexes)
CREATE TABLE IF NOT EXISTS projects (
    tenant_id BIGINT NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    workspace_id BIGINT NOT NULL,
    slug TEXT NOT NULL CHECK (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$' AND char_length(slug) <= 64),
    name TEXT NOT NULL CHECK (char_length(btrim(name)) BETWEEN 1 AND 128),
    platform TEXT NOT NULL DEFAULT 'other' CHECK (char_length(btrim(platform)) BETWEEN 1 AND 64),
    dsn_public_key TEXT NOT NULL UNIQUE CHECK (char_length(btrim(dsn_public_key)) BETWEEN 16 AND 128),
    retention_days_override SMALLINT CHECK (
        retention_days_override IS NULL OR (retention_days_override BETWEEN 1 AND 3650)
    ),
    rate_limit_per_minute INTEGER NOT NULL DEFAULT 1200 CHECK (rate_limit_per_minute BETWEEN 1 AND 1000000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (tenant_id, id),
    UNIQUE (tenant_id, workspace_id, slug),
    FOREIGN KEY (tenant_id, workspace_id) REFERENCES workspaces(tenant_id, id) ON DELETE CASCADE
);

CREATE UNIQUE INDEX IF NOT EXISTS projects_id_unique_idx ON projects (id);

-- 4. Users
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT NOT NULL UNIQUE CHECK (position('@' IN email) > 1 AND char_length(email) <= 254),
    name TEXT NOT NULL CHECK (char_length(btrim(name)) BETWEEN 1 AND 128),
    password_hash TEXT NOT NULL CHECK (char_length(password_hash) >= 32),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 5. Memberships (tenant or workspace scoped roles)
CREATE TABLE IF NOT EXISTS memberships (
    tenant_id BIGINT NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    workspace_id BIGINT,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    role TEXT NOT NULL CHECK (role IN ('tenant_owner', 'tenant_admin', 'workspace_admin', 'member', 'viewer')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (tenant_id, id),
    FOREIGN KEY (tenant_id, workspace_id) REFERENCES workspaces(tenant_id, id) ON DELETE CASCADE,
    CHECK (
        (workspace_id IS NULL AND role IN ('tenant_owner', 'tenant_admin', 'member', 'viewer'))
        OR (workspace_id IS NOT NULL AND role IN ('workspace_admin', 'member', 'viewer'))
    )
);

CREATE UNIQUE INDEX IF NOT EXISTS memberships_tenant_user_unique_idx
    ON memberships (tenant_id, user_id) WHERE workspace_id IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS memberships_workspace_user_unique_idx
    ON memberships (tenant_id, workspace_id, user_id) WHERE workspace_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS memberships_user_tenant_idx ON memberships (user_id, tenant_id);

-- 6. Sessions (tenant-scoped session tokens + CSRF)
CREATE TABLE IF NOT EXISTS sessions (
    tenant_id BIGINT NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    token_hash TEXT NOT NULL UNIQUE CHECK (char_length(token_hash) >= 32),
    csrf_token TEXT NOT NULL CHECK (char_length(csrf_token) >= 32),
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (tenant_id, id)
);

CREATE INDEX IF NOT EXISTS sessions_tenant_expires_idx ON sessions (tenant_id, expires_at);
CREATE INDEX IF NOT EXISTS sessions_user_id_idx ON sessions (user_id);

-- 7. Issues (leading tenant_id + project_id on primary key and all indexes)
CREATE TABLE IF NOT EXISTS issues (
    tenant_id BIGINT NOT NULL,
    project_id BIGINT NOT NULL,
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    fingerprint TEXT NOT NULL CHECK (char_length(btrim(fingerprint)) BETWEEN 1 AND 256),
    title TEXT NOT NULL CHECK (char_length(btrim(title)) >= 1),
    exception_type TEXT NOT NULL DEFAULT '',
    exception_value TEXT NOT NULL DEFAULT '',
    culprit TEXT NOT NULL DEFAULT '',
    level TEXT NOT NULL DEFAULT 'error' CHECK (level IN ('fatal', 'error', 'warning', 'info', 'debug')),
    status TEXT NOT NULL DEFAULT 'unresolved' CHECK (status IN ('unresolved', 'resolved', 'ignored')),
    is_regressed BOOLEAN NOT NULL DEFAULT FALSE,
    event_count BIGINT NOT NULL DEFAULT 1 CHECK (event_count >= 0),
    stored_full_events INTEGER NOT NULL DEFAULT 0 CHECK (stored_full_events >= 0),
    first_seen TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_seen TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_environment TEXT NOT NULL DEFAULT 'production',
    last_release TEXT,
    sample_event_id TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (tenant_id, project_id, id),
    UNIQUE (tenant_id, project_id, fingerprint),
    FOREIGN KEY (tenant_id, project_id) REFERENCES projects(tenant_id, id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS issues_tenant_project_status_last_seen_idx
    ON issues (tenant_id, project_id, status, last_seen DESC);
CREATE INDEX IF NOT EXISTS issues_tenant_project_env_release_idx
    ON issues (tenant_id, project_id, last_environment, last_release);

-- 8. Events (daily-partitioned by received_at; leading tenant_id + project_id on PK and indexes)
CREATE TABLE IF NOT EXISTS events (
    tenant_id BIGINT NOT NULL,
    project_id BIGINT NOT NULL,
    issue_id BIGINT NOT NULL,
    event_id TEXT NOT NULL CHECK (char_length(btrim(event_id)) BETWEEN 1 AND 128),
    received_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    environment TEXT NOT NULL DEFAULT 'production',
    release TEXT,
    level TEXT NOT NULL DEFAULT 'error' CHECK (level IN ('fatal', 'error', 'warning', 'info', 'debug')),
    platform TEXT NOT NULL DEFAULT 'other',
    exception_type TEXT NOT NULL DEFAULT '',
    exception_value TEXT NOT NULL DEFAULT '',
    stack_frames JSONB NOT NULL DEFAULT '[]'::jsonb,
    tags JSONB NOT NULL DEFAULT '{}'::jsonb,
    payload JSONB NOT NULL DEFAULT '{}'::jsonb,
    is_sample BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (tenant_id, project_id, received_at, event_id),
    FOREIGN KEY (tenant_id, project_id, issue_id) REFERENCES issues(tenant_id, project_id, id) ON DELETE CASCADE
) PARTITION BY RANGE (received_at);

CREATE INDEX IF NOT EXISTS events_tenant_project_issue_received_idx
    ON events (tenant_id, project_id, issue_id, received_at DESC);

-- 9. Issue Hourly Counters (leading tenant_id + project_id on PK and indexes)
CREATE TABLE IF NOT EXISTS issue_hourly_counters (
    tenant_id BIGINT NOT NULL,
    project_id BIGINT NOT NULL,
    issue_id BIGINT NOT NULL,
    hour_bucket TIMESTAMPTZ NOT NULL,
    event_count BIGINT NOT NULL DEFAULT 0 CHECK (event_count >= 0),
    PRIMARY KEY (tenant_id, project_id, issue_id, hour_bucket),
    FOREIGN KEY (tenant_id, project_id, issue_id) REFERENCES issues(tenant_id, project_id, id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS issue_hourly_counters_tenant_project_bucket_idx
    ON issue_hourly_counters (tenant_id, project_id, hour_bucket DESC);

