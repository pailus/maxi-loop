-- 0003_phase2_pii_releases_alerts.sql
-- Phase 2 schema additions:
--   - Configurable inherited PII scrub rules (tenant -> workspace -> project)
--   - Release tracking (`releases`, `issue_releases`, and `issues.first_release`)
--   - Alert channels (`webhook`, `telegram`, `email`), alert rules (`new_issue`, `regression`, `spike`),
--     and `alert_deliveries` audit/cooldown log
--   - Row-Level Security (`maxi_loop_app` tenant isolation + `maxi_loop_worker` cross-tenant worker)

-- 1. Extend `issues` with `first_release` (backward-compatible nullable column)
ALTER TABLE issues ADD COLUMN IF NOT EXISTS first_release TEXT;

UPDATE issues
SET first_release = last_release
WHERE first_release IS NULL AND last_release IS NOT NULL;

-- 2. Configurable PII Scrub Rules (inherited tenant -> workspace -> project; additive to mandatory baseline)
CREATE TABLE IF NOT EXISTS pii_scrub_rules (
    tenant_id BIGINT NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    workspace_id BIGINT,
    project_id BIGINT,
    name TEXT NOT NULL CHECK (char_length(btrim(name)) BETWEEN 1 AND 128),
    rule_type TEXT NOT NULL CHECK (rule_type IN ('field_name', 'header_name', 'value_substring')),
    pattern TEXT NOT NULL CHECK (char_length(btrim(pattern)) BETWEEN 2 AND 128),
    replacement TEXT NOT NULL DEFAULT '[Filtered]' CHECK (char_length(btrim(replacement)) BETWEEN 1 AND 64),
    is_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (tenant_id, id),
    FOREIGN KEY (tenant_id, workspace_id) REFERENCES workspaces(tenant_id, id) ON DELETE CASCADE,
    FOREIGN KEY (tenant_id, project_id) REFERENCES projects(tenant_id, id) ON DELETE CASCADE,
    CHECK (project_id IS NULL OR workspace_id IS NOT NULL)
);

CREATE INDEX IF NOT EXISTS pii_scrub_rules_tenant_scope_idx
    ON pii_scrub_rules (tenant_id, workspace_id, project_id, is_enabled);

-- 3. Releases (leading tenant_id + project_id on primary key and indexes)
CREATE TABLE IF NOT EXISTS releases (
    tenant_id BIGINT NOT NULL,
    project_id BIGINT NOT NULL,
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    version TEXT NOT NULL CHECK (char_length(btrim(version)) BETWEEN 1 AND 128),
    commit_sha TEXT CHECK (commit_sha IS NULL OR commit_sha ~ '^[0-9a-fA-F]{7,40}$'),
    environment TEXT CHECK (environment IS NULL OR char_length(btrim(environment)) BETWEEN 1 AND 64),
    notes TEXT NOT NULL DEFAULT '' CHECK (char_length(notes) <= 2000),
    first_seen TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_seen TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    deployed_at TIMESTAMPTZ,
    event_count BIGINT NOT NULL DEFAULT 0 CHECK (event_count >= 0),
    new_issues_count BIGINT NOT NULL DEFAULT 0 CHECK (new_issues_count >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (tenant_id, project_id, id),
    UNIQUE (tenant_id, project_id, version),
    FOREIGN KEY (tenant_id, project_id) REFERENCES projects(tenant_id, id) ON DELETE CASCADE
);

CREATE UNIQUE INDEX IF NOT EXISTS releases_id_unique_idx ON releases (id);
CREATE INDEX IF NOT EXISTS releases_tenant_project_last_seen_idx
    ON releases (tenant_id, project_id, last_seen DESC);

-- 4. Issue <-> Release linking table
CREATE TABLE IF NOT EXISTS issue_releases (
    tenant_id BIGINT NOT NULL,
    project_id BIGINT NOT NULL,
    issue_id BIGINT NOT NULL,
    release_version TEXT NOT NULL CHECK (char_length(btrim(release_version)) BETWEEN 1 AND 128),
    first_seen TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_seen TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    event_count BIGINT NOT NULL DEFAULT 0 CHECK (event_count >= 0),
    PRIMARY KEY (tenant_id, project_id, issue_id, release_version),
    FOREIGN KEY (tenant_id, project_id, issue_id) REFERENCES issues(tenant_id, project_id, id) ON DELETE CASCADE,
    FOREIGN KEY (tenant_id, project_id, release_version) REFERENCES releases(tenant_id, project_id, version) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS issue_releases_tenant_project_version_idx
    ON issue_releases (tenant_id, project_id, release_version, last_seen DESC);

-- 5. Alert Channels (inherited tenant -> workspace -> project; webhook, telegram, email)
CREATE TABLE IF NOT EXISTS alert_channels (
    tenant_id BIGINT NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    workspace_id BIGINT,
    project_id BIGINT,
    name TEXT NOT NULL CHECK (char_length(btrim(name)) BETWEEN 1 AND 128),
    channel_type TEXT NOT NULL CHECK (channel_type IN ('webhook', 'telegram', 'email')),
    config JSONB NOT NULL DEFAULT '{}'::jsonb,
    is_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (tenant_id, id),
    FOREIGN KEY (tenant_id, workspace_id) REFERENCES workspaces(tenant_id, id) ON DELETE CASCADE,
    FOREIGN KEY (tenant_id, project_id) REFERENCES projects(tenant_id, id) ON DELETE CASCADE,
    CHECK (project_id IS NULL OR workspace_id IS NOT NULL)
);

CREATE INDEX IF NOT EXISTS alert_channels_tenant_scope_idx
    ON alert_channels (tenant_id, workspace_id, project_id, is_enabled);

-- 6. Alert Rules (new_issue, regression, spike)
CREATE TABLE IF NOT EXISTS alert_rules (
    tenant_id BIGINT NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    workspace_id BIGINT,
    project_id BIGINT,
    channel_id BIGINT NOT NULL,
    name TEXT NOT NULL CHECK (char_length(btrim(name)) BETWEEN 1 AND 128),
    trigger_type TEXT NOT NULL CHECK (trigger_type IN ('new_issue', 'regression', 'spike')),
    environment_filter TEXT CHECK (environment_filter IS NULL OR char_length(btrim(environment_filter)) BETWEEN 1 AND 64),
    spike_threshold INTEGER CHECK (spike_threshold IS NULL OR spike_threshold BETWEEN 2 AND 1000000),
    spike_window_minutes INTEGER CHECK (spike_window_minutes IS NULL OR spike_window_minutes BETWEEN 1 AND 1440),
    cooldown_minutes INTEGER NOT NULL DEFAULT 15 CHECK (cooldown_minutes BETWEEN 1 AND 1440),
    is_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (tenant_id, id),
    FOREIGN KEY (tenant_id, workspace_id) REFERENCES workspaces(tenant_id, id) ON DELETE CASCADE,
    FOREIGN KEY (tenant_id, project_id) REFERENCES projects(tenant_id, id) ON DELETE CASCADE,
    FOREIGN KEY (tenant_id, channel_id) REFERENCES alert_channels(tenant_id, id) ON DELETE CASCADE,
    CHECK (project_id IS NULL OR workspace_id IS NOT NULL),
    CHECK (
        (trigger_type = 'spike' AND spike_threshold IS NOT NULL AND spike_window_minutes IS NOT NULL)
        OR (trigger_type IN ('new_issue', 'regression'))
    )
);

CREATE INDEX IF NOT EXISTS alert_rules_tenant_trigger_idx
    ON alert_rules (tenant_id, trigger_type, is_enabled);

-- 7. Alert Deliveries (audit log + cooldown deduplication)
CREATE TABLE IF NOT EXISTS alert_deliveries (
    tenant_id BIGINT NOT NULL,
    project_id BIGINT NOT NULL,
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    rule_id BIGINT NOT NULL,
    channel_id BIGINT NOT NULL,
    issue_id BIGINT NOT NULL,
    trigger_type TEXT NOT NULL CHECK (trigger_type IN ('new_issue', 'regression', 'spike')),
    channel_type TEXT NOT NULL CHECK (channel_type IN ('webhook', 'telegram', 'email')),
    status TEXT NOT NULL CHECK (status IN ('sent', 'failed', 'skipped')),
    http_status INTEGER,
    error_message TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (tenant_id, project_id, id),
    FOREIGN KEY (tenant_id, project_id, issue_id) REFERENCES issues(tenant_id, project_id, id) ON DELETE CASCADE,
    FOREIGN KEY (tenant_id, rule_id) REFERENCES alert_rules(tenant_id, id) ON DELETE CASCADE,
    FOREIGN KEY (tenant_id, channel_id) REFERENCES alert_channels(tenant_id, id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS alert_deliveries_cooldown_idx
    ON alert_deliveries (tenant_id, project_id, rule_id, issue_id, created_at DESC);
CREATE INDEX IF NOT EXISTS alert_deliveries_tenant_created_idx
    ON alert_deliveries (tenant_id, created_at DESC);

-- Enable & Force Row-Level Security on all new Phase 2 tables
DO $$
DECLARE
    tbl TEXT;
BEGIN
    FOREACH tbl IN ARRAY ARRAY[
        'pii_scrub_rules',
        'releases',
        'issue_releases',
        'alert_channels',
        'alert_rules',
        'alert_deliveries'
    ]
    LOOP
        EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', tbl);
        EXECUTE format('ALTER TABLE %I FORCE ROW LEVEL SECURITY', tbl);

        EXECUTE format('DROP POLICY IF EXISTS tenant_isolation_policy ON %I', tbl);
        EXECUTE format(
            'CREATE POLICY tenant_isolation_policy ON %I AS PERMISSIVE FOR ALL TO maxi_loop_app '
            'USING (tenant_id = app_current_tenant_id()) '
            'WITH CHECK (tenant_id = app_current_tenant_id())',
            tbl
        );

        EXECUTE format('DROP POLICY IF EXISTS worker_cross_tenant_policy ON %I', tbl);
        EXECUTE format(
            'CREATE POLICY worker_cross_tenant_policy ON %I AS PERMISSIVE FOR ALL TO maxi_loop_worker '
            'USING (true) '
            'WITH CHECK (tenant_id > 0)',
            tbl
        );

        EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE %I TO maxi_loop_app, maxi_loop_worker', tbl);
    END LOOP;
END
$$;

GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO maxi_loop_app, maxi_loop_worker;
