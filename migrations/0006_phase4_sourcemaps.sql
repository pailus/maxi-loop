-- 0006_phase4_sourcemaps.sql
-- Phase 4 schema additions:
--   - Release-scoped React/JS Source Maps (`source_maps`), matched by `(release_version, filename)` or `debug_id`
--   - Stored zstd-compressed in PostgreSQL (`content_zstd BYTEA`) with leading `(tenant_id, project_id)` keys/indexes
--   - Row-Level Security (`maxi_loop_app` tenant isolation + `maxi_loop_worker` ingest-time resolution)

CREATE TABLE IF NOT EXISTS source_maps (
    tenant_id BIGINT NOT NULL,
    project_id BIGINT NOT NULL,
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    release_version TEXT NOT NULL CHECK (
        char_length(btrim(release_version)) BETWEEN 1 AND 128
        AND release_version !~ '\s'
    ),
    filename TEXT NOT NULL CHECK (char_length(btrim(filename)) BETWEEN 1 AND 512),
    debug_id TEXT CHECK (debug_id IS NULL OR char_length(btrim(debug_id)) BETWEEN 8 AND 64),
    sha256 TEXT NOT NULL CHECK (char_length(sha256) = 64),
    raw_size_bytes INTEGER NOT NULL CHECK (raw_size_bytes > 0),
    compressed_size_bytes INTEGER NOT NULL CHECK (compressed_size_bytes > 0),
    content_zstd BYTEA NOT NULL,
    uploaded_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (tenant_id, project_id, id),
    UNIQUE (tenant_id, project_id, release_version, filename),
    FOREIGN KEY (tenant_id, project_id) REFERENCES projects(tenant_id, id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS source_maps_tenant_project_release_idx
    ON source_maps (tenant_id, project_id, release_version, updated_at DESC);

CREATE INDEX IF NOT EXISTS source_maps_tenant_project_debug_id_idx
    ON source_maps (tenant_id, project_id, debug_id)
    WHERE debug_id IS NOT NULL;

ALTER TABLE source_maps ENABLE ROW LEVEL SECURITY;
ALTER TABLE source_maps FORCE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS tenant_isolation_policy ON source_maps;
CREATE POLICY tenant_isolation_policy ON source_maps
    AS PERMISSIVE FOR ALL TO maxi_loop_app
    USING (tenant_id = app_current_tenant_id())
    WITH CHECK (tenant_id = app_current_tenant_id());

DROP POLICY IF EXISTS worker_cross_tenant_policy ON source_maps;
CREATE POLICY worker_cross_tenant_policy ON source_maps
    AS PERMISSIVE FOR ALL TO maxi_loop_worker
    USING (true)
    WITH CHECK (tenant_id > 0);

GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE source_maps TO maxi_loop_app, maxi_loop_worker;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO maxi_loop_app, maxi_loop_worker;
