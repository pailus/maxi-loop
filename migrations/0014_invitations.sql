-- 0014_invitations.sql
-- F022: invite-by-link onboarding. Only the SHA-256 of the invite token is stored; the raw
-- token is shown once to the inviting admin. Invites are single-use and expire.

CREATE TABLE IF NOT EXISTS invitations (
    tenant_id BIGINT NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    workspace_id BIGINT,
    email TEXT NOT NULL CHECK (position('@' IN email) > 1 AND char_length(email) <= 254),
    role TEXT NOT NULL CHECK (role IN ('tenant_owner', 'tenant_admin', 'workspace_admin', 'member', 'viewer')),
    token_hash TEXT NOT NULL UNIQUE CHECK (char_length(token_hash) = 64),
    invited_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    accepted_at TIMESTAMPTZ,
    accepted_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    revoked_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (tenant_id, id),
    FOREIGN KEY (tenant_id, workspace_id) REFERENCES workspaces(tenant_id, id) ON DELETE CASCADE,
    CHECK (
        (workspace_id IS NULL AND role IN ('tenant_owner', 'tenant_admin', 'member', 'viewer'))
        OR (workspace_id IS NOT NULL AND role IN ('workspace_admin', 'member', 'viewer'))
    )
);

-- At most one open invite per email and scope; re-inviting revokes the previous one first.
CREATE UNIQUE INDEX IF NOT EXISTS invitations_open_scope_email_idx
    ON invitations (tenant_id, COALESCE(workspace_id, 0), email)
    WHERE accepted_at IS NULL AND revoked_at IS NULL;

CREATE INDEX IF NOT EXISTS invitations_tenant_created_idx
    ON invitations (tenant_id, created_at DESC);

ALTER TABLE invitations ENABLE ROW LEVEL SECURITY;
ALTER TABLE invitations FORCE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS tenant_isolation_policy ON invitations;
CREATE POLICY tenant_isolation_policy ON invitations
    AS PERMISSIVE FOR ALL TO maxi_loop_app
    USING (tenant_id = app_current_tenant_id())
    WITH CHECK (tenant_id = app_current_tenant_id());

DROP POLICY IF EXISTS worker_cross_tenant_policy ON invitations;
CREATE POLICY worker_cross_tenant_policy ON invitations
    AS PERMISSIVE FOR ALL TO maxi_loop_worker
    USING (true)
    WITH CHECK (tenant_id > 0);

GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE invitations TO maxi_loop_app, maxi_loop_worker;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO maxi_loop_app, maxi_loop_worker;
