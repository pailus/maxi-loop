-- 0007_phase5_rbac_settings_tokens.sql
-- Phase 5:
--   - Inherited rate limits (tenant default + aggregate tenant cap -> workspace override -> project override)
--   - Per-project API tokens (`api_tokens`, SHA-256 hash only, read/write scopes, expiry & revocation) with RLS

-- 1. Inherited rate limit settings on tenants, workspaces, and projects (backward-compatible)
ALTER TABLE tenants
    ADD COLUMN IF NOT EXISTS default_rate_limit_per_minute INTEGER NOT NULL DEFAULT 1200
        CHECK (default_rate_limit_per_minute BETWEEN 1 AND 1000000);

ALTER TABLE tenants
    ADD COLUMN IF NOT EXISTS aggregate_rate_limit_per_minute INTEGER NOT NULL DEFAULT 6000
        CHECK (aggregate_rate_limit_per_minute BETWEEN 1 AND 10000000);

ALTER TABLE workspaces
    ADD COLUMN IF NOT EXISTS default_rate_limit_per_minute_override INTEGER
        CHECK (
            default_rate_limit_per_minute_override IS NULL
            OR default_rate_limit_per_minute_override BETWEEN 1 AND 1000000
        );

ALTER TABLE projects
    ADD COLUMN IF NOT EXISTS rate_limit_per_minute_override INTEGER
        CHECK (
            rate_limit_per_minute_override IS NULL
            OR rate_limit_per_minute_override BETWEEN 1 AND 1000000
        );

-- Preserve any pre-existing custom per-project rate limits as explicit overrides while letting default 1200 inherit.
UPDATE projects
SET rate_limit_per_minute_override = rate_limit_per_minute
WHERE rate_limit_per_minute <> 1200
  AND rate_limit_per_minute_override IS NULL;

-- 2. Per-project API tokens (F-ADM-4: SHA-256 hash only, revocable, scoped strictly to one project)
CREATE TABLE IF NOT EXISTS api_tokens (
    tenant_id BIGINT NOT NULL,
    project_id BIGINT NOT NULL,
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    created_by_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name TEXT NOT NULL CHECK (char_length(btrim(name)) BETWEEN 1 AND 128),
    token_prefix TEXT NOT NULL CHECK (char_length(token_prefix) BETWEEN 8 AND 24),
    token_hash TEXT NOT NULL UNIQUE CHECK (char_length(token_hash) = 64),
    can_read BOOLEAN NOT NULL DEFAULT TRUE,
    can_write BOOLEAN NOT NULL DEFAULT FALSE,
    expires_at TIMESTAMPTZ,
    revoked_at TIMESTAMPTZ,
    last_used_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (tenant_id, project_id, id),
    FOREIGN KEY (tenant_id, project_id) REFERENCES projects(tenant_id, id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS api_tokens_tenant_project_created_idx
    ON api_tokens (tenant_id, project_id, created_at DESC);

CREATE INDEX IF NOT EXISTS api_tokens_tenant_id_idx
    ON api_tokens (tenant_id, id);

ALTER TABLE api_tokens ENABLE ROW LEVEL SECURITY;
ALTER TABLE api_tokens FORCE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS tenant_isolation_policy ON api_tokens;
CREATE POLICY tenant_isolation_policy ON api_tokens
    AS PERMISSIVE FOR ALL TO maxi_loop_app
    USING (tenant_id = app_current_tenant_id())
    WITH CHECK (tenant_id = app_current_tenant_id());

DROP POLICY IF EXISTS worker_cross_tenant_policy ON api_tokens;
CREATE POLICY worker_cross_tenant_policy ON api_tokens
    AS PERMISSIVE FOR ALL TO maxi_loop_worker
    USING (true)
    WITH CHECK (tenant_id > 0);

GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE api_tokens TO maxi_loop_app, maxi_loop_worker;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO maxi_loop_app, maxi_loop_worker;
