-- 0004_phase2b_mcp.sql
-- Phase 2b schema additions:
--   - Revocable scoped MCP Bearer tokens (`mcp_tokens`, SHA-256 hash only)
--   - MCP tool invocation audit logs (`mcp_audit_logs`)
--   - Issue triage/analysis notes (`issue_notes`, shared by UI and MCP)
--   - Row-Level Security (`maxi_loop_app` tenant isolation + `maxi_loop_worker` lookup role)

-- 1. MCP Bearer Tokens (raw token is never stored; only SHA-256 hex digest + display prefix)
CREATE TABLE IF NOT EXISTS mcp_tokens (
    tenant_id BIGINT NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name TEXT NOT NULL CHECK (char_length(btrim(name)) BETWEEN 1 AND 128),
    token_prefix TEXT NOT NULL CHECK (char_length(token_prefix) BETWEEN 6 AND 24),
    token_hash TEXT NOT NULL UNIQUE CHECK (char_length(token_hash) = 64),
    access_scope TEXT NOT NULL CHECK (access_scope IN ('tenant', 'workspace', 'project')),
    workspace_id BIGINT,
    project_id BIGINT,
    can_read BOOLEAN NOT NULL DEFAULT TRUE,
    can_triage BOOLEAN NOT NULL DEFAULT FALSE,
    rate_limit_per_minute INTEGER NOT NULL DEFAULT 60 CHECK (rate_limit_per_minute BETWEEN 1 AND 6000),
    expires_at TIMESTAMPTZ,
    revoked_at TIMESTAMPTZ,
    last_used_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (tenant_id, id),
    FOREIGN KEY (tenant_id, workspace_id) REFERENCES workspaces(tenant_id, id) ON DELETE CASCADE,
    FOREIGN KEY (tenant_id, project_id) REFERENCES projects(tenant_id, id) ON DELETE CASCADE,
    CHECK (
        (access_scope = 'tenant' AND workspace_id IS NULL AND project_id IS NULL)
        OR (access_scope = 'workspace' AND workspace_id IS NOT NULL AND project_id IS NULL)
        OR (access_scope = 'project' AND workspace_id IS NOT NULL AND project_id IS NOT NULL)
    )
);

CREATE INDEX IF NOT EXISTS mcp_tokens_tenant_user_idx
    ON mcp_tokens (tenant_id, user_id, created_at DESC);

-- 2. MCP Audit Logs (records every MCP tool call, authorization denial, and rate limit)
CREATE TABLE IF NOT EXISTS mcp_audit_logs (
    tenant_id BIGINT NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    token_id BIGINT,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    user_email TEXT NOT NULL CHECK (char_length(btrim(user_email)) BETWEEN 3 AND 254),
    token_name TEXT NOT NULL CHECK (char_length(btrim(token_name)) BETWEEN 1 AND 128),
    tool_name TEXT NOT NULL CHECK (char_length(btrim(tool_name)) BETWEEN 1 AND 128),
    arguments_json JSONB NOT NULL DEFAULT '{}'::jsonb,
    status TEXT NOT NULL CHECK (status IN ('ok', 'error', 'denied', 'rate_limited')),
    error_code TEXT CHECK (error_code IS NULL OR char_length(error_code) <= 128),
    duration_ms INTEGER NOT NULL DEFAULT 0 CHECK (duration_ms >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (tenant_id, id),
    FOREIGN KEY (tenant_id, token_id) REFERENCES mcp_tokens(tenant_id, id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS mcp_audit_logs_tenant_created_idx
    ON mcp_audit_logs (tenant_id, created_at DESC);

-- 3. Issue Notes (shared by UI and MCP `add_issue_note` / `update_issue_status`)
CREATE TABLE IF NOT EXISTS issue_notes (
    tenant_id BIGINT NOT NULL,
    project_id BIGINT NOT NULL,
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    issue_id BIGINT NOT NULL,
    author_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    author_email TEXT NOT NULL CHECK (char_length(btrim(author_email)) BETWEEN 3 AND 254),
    source TEXT NOT NULL DEFAULT 'ui' CHECK (source IN ('ui', 'mcp')),
    body TEXT NOT NULL CHECK (char_length(btrim(body)) BETWEEN 1 AND 4000),
    commit_ref TEXT CHECK (commit_ref IS NULL OR char_length(btrim(commit_ref)) BETWEEN 1 AND 128),
    status_change TEXT CHECK (status_change IS NULL OR status_change IN ('unresolved', 'resolved', 'ignored')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (tenant_id, project_id, id),
    FOREIGN KEY (tenant_id, project_id, issue_id) REFERENCES issues(tenant_id, project_id, id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS issue_notes_tenant_project_issue_idx
    ON issue_notes (tenant_id, project_id, issue_id, created_at DESC);

-- Enable & Force Row-Level Security on all new Phase 2b tables
DO $$
DECLARE
    tbl TEXT;
BEGIN
    FOREACH tbl IN ARRAY ARRAY[
        'mcp_tokens',
        'mcp_audit_logs',
        'issue_notes'
    ]
    LOOP
        EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', tbl);
        EXECUTE format('ALTER TABLE %I FORCE ROW LEVEL SECURITY', tbl);

        EXECUTE format('DROP POLICY IF EXISTS tenant_isolation_policy ON %I', tbl);
        EXECUTE format(
            'CREATE POLICY tenant_isolation_policy ON %I AS PERMISSIVE FOR ALL TO maxi_loop_app '
            'USING (tenant_id = app_current_tenant_id()) '
            'WITH CHECK (tenant_id = app_current_tenant_id())',
            tbl
        );

        EXECUTE format('DROP POLICY IF EXISTS worker_cross_tenant_policy ON %I', tbl);
        EXECUTE format(
            'CREATE POLICY worker_cross_tenant_policy ON %I AS PERMISSIVE FOR ALL TO maxi_loop_worker '
            'USING (true) '
            'WITH CHECK (tenant_id > 0)',
            tbl
        );

        EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE %I TO maxi_loop_app, maxi_loop_worker', tbl);
    END LOOP;
END
$$;

GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO maxi_loop_app, maxi_loop_worker;
